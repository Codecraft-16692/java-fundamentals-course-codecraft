public class MiPrograma {
    public static void main(String[] args) {

        // Cada println muestra una línea nueva en la pantalla
        System.out.println("Hola, soy un programa hecho en Java");
        System.out.println("Me gusta jugar videojuegos");
        System.out.println("Mi comida favorita es la pizza");

        // Una línea vacía para separar
        System.out.println();

        // print (sin ln) NO salta de línea
        System.out.print("Esto va ");
        System.out.print("en la misma línea");
        System.out.println();

    }
}
